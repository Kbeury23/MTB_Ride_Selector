import json
import os
import random
import streamlit as st

FILE_NAME = "LocationList.json"

def load_locations():
  if os.path.exists(FILE_NAME):
    with open(FILE_NAME, "r") as file:
      return json.load(file)
  return ["Blue Marsh", "Birdsboro Preserve", "Shillington Trail Loop", "Schuylkill River Trail", "Ride a New Path at Any Location"]

def save_locations(locations):
    with open(FILE_NAME, "w") as file:
      json.dump(locations, file, indent =4)


def main():

  st.title("MTB Ride Selector")

  if "locations"not in st.session_state:
    st.session_state.locations = load_locations()

  #1. selector
  if st.button("Select Your Next Ride"):
    if st.session_state.locations:
        st.success(f"Your Next Ride Should be at: {random.choice(st.session_state.locations)}")
    else:
        st.warning("Your Location List is Empty!")

  st.divider()

#2. View Loc. List  
  if st.button("View Location List"):
    for loc in st.session_state.locations:
      st.write(f"- {loc}")

  st.divider()

#3. Add Loc.
  st.subheader("Add Location")
  new_loc = st.text_input("Enter Your New Location Name:", key = "add_loc_input").strip()
  if st.button("Add Location"):
    if new_loc:
        st.session_state.locations.append(new_loc)
        save_locations(st.session_state.locations)
        st.rerun()
    else:
        st.warning("Please Enter A Location Name!")


#4. Delete Loc.
  st.subheader("Remove Location")
  if st.session_state.locations:
     delete_loc = st.selectbox("Select Location to Delete", st.session_state.locations, key="del_loc_select")
     if st.button("Remove Location"):
      st.session_state.locations.remove(delete_loc)
      save_locations(st.session_state.locations)
      st.rerun()

#5 Exit Button
  if st.button("Exit"):
    st.write("Enjoy Your Ride!")
    os._exit(0)    

if __name__ == "__main__":
    main()